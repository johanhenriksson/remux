package config

import (
	"os"
	"path/filepath"
	"testing"
)

func TestWriteEnvFile(t *testing.T) {
	path := filepath.Join(t.TempDir(), "sub", ".env.local")
	err := WriteEnvFile(path, map[string]string{
		"PORT":    "11010",
		"URL":     "http://localhost:11010/x?a=b",
		"SPACED":  "hello world",
		"QUOTE":   "it's $HOME",
		"EMPTY":   "",
		"DB_NAME": "app_feat",
	})
	if err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	want := `# Generated by remux. Changes are overwritten when the workspace is recreated.
DB_NAME=app_feat
EMPTY=
PORT=11010
QUOTE="it's \$HOME"
SPACED='hello world'
URL='http://localhost:11010/x?a=b'
`
	if string(data) != want {
		t.Fatalf("got:\n%s\nwant:\n%s", data, want)
	}
}

func TestMergeBackendAndEnvFile(t *testing.T) {
	base := &Config{Backend: "tmux", EnvFile: ".env"}
	got := merge(base, &Config{Backend: "herdr"})
	if got.Backend != "herdr" || got.EnvFile != ".env" {
		t.Fatalf("got backend=%q env_file=%q", got.Backend, got.EnvFile)
	}
	got = merge(base, &Config{EnvFile: ".env.local"})
	if got.Backend != "tmux" || got.EnvFile != ".env.local" {
		t.Fatalf("got backend=%q env_file=%q", got.Backend, got.EnvFile)
	}
}
