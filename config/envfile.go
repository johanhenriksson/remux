package config

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var bareEnvValue = regexp.MustCompile(`^[A-Za-z0-9_./:@,+=-]*$`)

// WriteEnvFile writes env as a dotenv file at path, sorted by key.
// Values are quoted when needed so that common dotenv parsers read them back
// verbatim.
func WriteEnvFile(path string, env map[string]string) error {
	keys := make([]string, 0, len(env))
	for k := range env {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("# Generated by remux. Changes are overwritten when the workspace is recreated.\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "%s=%s\n", k, quoteEnvValue(env[k]))
	}

	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(b.String()), 0644)
}

func quoteEnvValue(v string) string {
	if bareEnvValue.MatchString(v) {
		return v
	}
	// Single quotes are literal in dotenv parsers (no expansion, no escapes).
	if !strings.ContainsAny(v, "'\n") {
		return "'" + v + "'"
	}
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`, "\n", `\n`)
	return `"` + r.Replace(v) + `"`
}
